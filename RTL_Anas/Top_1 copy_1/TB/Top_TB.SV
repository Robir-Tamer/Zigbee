`timescale 1ns/1ps

// ============================================================================
// TESTBENCH: Top_TB  (payload1.txt / payload2.txt DQPSK-input-format variant)
// PURPOSE  : Self-checking verification of the full CSS PHY transmitter
//            chain (DQPSK differential encoder -> dual Sync FIFOs (I/Q) ->
//            CSK_GEN chirp ROM/frame generator -> complex multiplier ->
//            tx_real/tx_imag), driven directly at the DQPSK's raw QPSK
//            symbol inputs (Real, Imag).
//
// STIMULUS SOURCE: this version reads pre-computed (Real, Imag) symbol
// pairs directly from a file -- payload1.txt (1 Mb/s) or payload2.txt
// (250 kb/s) -- generated by the MATLAB golden model's front-end pipeline
// (Zero Padding -> Demux -> Symbol Mapper -> Interleaver -> Form PPDU ->
// QPSK Mapper). Each non-comment line is "<Real> <Imag>", already the
// exact X_n values that feed DQPSK -- no bit-to-symbol conversion is
// needed here, unlike the raw-payload-bits variant of this testbench.
//
// *** TO SWITCH DATA RATE: change PAYLOAD_FILE below ***
//     1 Mb/s   (dataRate=0) -> PAYLOAD_FILE = "../TB/payload1.txt"
//     250 kb/s (dataRate=1) -> PAYLOAD_FILE = "../TB/payload2.txt"
// This is the ONLY line that needs to change between the two scenarios.
//
// HOW THE SELF-CHECKING WORKS (unchanged from the original -- three
// independent checks, all running concurrently against the same DUT run):
//   1. DQPSK correctness  : a golden differential-encoder model is computed
//      in this testbench (task send_symbol), pushed into a queue, and
//      compared cycle-by-cycle against the DUT's actual Real_o/Imag_o.
//   2. Multiplier correctness : every time a new symbol is latched by
//      CSK_GEN (next_item pulses), this TB independently recomputes the
//      expected complex product (S_R+jS_I)*(csk_out_r+j csk_out_i) and
//      compares it against the DUT's registered tx_real/tx_imag one cycle
//      later (accounting for the known 1-cycle multiplier latency).
//   3. Frame completion : tx_done is awaited explicitly after all symbols
//      from the file have been pushed, confirming the full frame
//      (including its mandatory trailing gap) actually completes.
// ============================================================================

module Top_TB #(
    parameter FIFO_DEPTH = 4096,
    parameter FIFO_WIDTH = 2,
    parameter WL         = 6
)();

    // *** CHANGE THIS LINE TO SWITCH DATA RATE ***
    // 1 Mb/s   -> "../TB/payload1.txt"
    // 250 kb/s -> "../TB/payload2.txt"
    localparam PAYLOAD_FILE = "../TB/payload1.txt";

    // ---- Clock and Reset Signals ----
    reg clk = 0;
    reg rst_n = 1;

    // ---- DUT Inputs ----
    reg i_valid = 0;
    reg signed [1:0] Real = 0;
    reg signed [1:0] Imag = 0;

    // ---- DUT Outputs ----
    wire tx_done, tx_end;
    wire signed [7:0] tx_real, tx_imag;

    // ---- Verification Counters & Flags ----
    integer pass_cnt = 0;
    integer fail_cnt = 0;
    integer symbol_index = 0;
    integer modulation_sample_cnt = 0;

    // ---- Expected Output Queues for Self-Checking Verification ----
    reg signed [1:0] exp_dqpsk_r [$];
    reg signed [1:0] exp_dqpsk_i [$];

    // ---- Reference Shift Registers matching DQPSK hardware model ----
    reg signed [1:0] ref_real_ff [0:3];
    reg signed [1:0] ref_imag_ff [0:3];

    // ---- Symbol stream loaded from the payload file, as (Real,Imag) pairs ----
    typedef struct packed { logic signed [1:0] r; logic signed [1:0] i; } sym_t;
    sym_t symbol_queue [$];
    integer num_symbols;
    integer num_blocks;

    // ---- DUT Instantiation ----
    Top #(
        .FIFO_DEPTH(FIFO_DEPTH),
        .FIFO_WIDTH(FIFO_WIDTH),
        .WL(WL)
    ) Top_DUT (
        .clk(clk),
        .rst_n(rst_n),
        .i_valid(i_valid),
        .Real(Real),
        .Imag(Imag),
        .tx_done(tx_done),
        .tx_end(tx_end),
        .tx_real(tx_real),
        .tx_imag(tx_imag)
    );

    // ---- 32 MHz Clock Generation (31.25 ns Period) ----
    always #15.625 clk = ~clk;

    // ========================================================================
    // GOLDEN-VECTOR OUTPUT WRITERS
    // ------------------------------------------------------------------------
    // Dumps tx_real/tx_imag in the exact same format as
    // tx_real_Q3p4_1Mbs.txt / tx_imag_Q3p4_1Mbs.txt (one 8-bit two's
    // complement binary string per line) for direct post-run diffing.
    //
    // WHY THE 2-CYCLE DELAY ON 'running':
    // tx_real is registered from (S_R, csk_out_r), which are themselves
    // registered from CSK_GEN's internal fetch (gated on 'running') --
    // that's a 2-cycle pipeline: running -> csk_out/S_R (1 cycle) ->
    // tx_real (1 more cycle). The golden MATLAB vector contains exactly
    // one sample per cycle CSK_GEN is "running" (active region + gap,
    // no leading/trailing padding) -- so capturing tx_real gated on
    // 'running' delayed by exactly 2 cycles reproduces that same count,
    // correctly aligned, with no extra startup-latency or post-tx_done
    // zero lines polluting the file. (Verified by cycle-accurate model:
    // running's own span and tx_real's valid-data span are the same
    // length, offset by exactly 2 cycles.)
    // ========================================================================
    integer fd_real, fd_imag;
    reg     running_d1, running_d2;

    initial begin
        fd_real = $fopen("tx_real_sim_output.txt", "w");
        fd_imag = $fopen("tx_imag_sim_output.txt", "w");
        if (fd_real == 0 || fd_imag == 0) begin
            $display("[ERROR] Could not open sim output files for writing.");
            $finish;
        end
    end

    always @(posedge clk) begin
        if (!rst_n) begin
            running_d1 <= 1'b0;
            running_d2 <= 1'b0;
        end else begin
            running_d1 <= Top_DUT.CSK_GEN_DUT.running;
            running_d2 <= running_d1;
        end
    end

    // ------------------------------------------------------------------------
    // WHY A ONE-CYCLE HOLD BUFFER, NOT A DIRECT WRITE:
    // 'running' stays asserted for one extra cycle beyond the last real
    // gap sample before it finally drops (the cycle where stop_now's
    // condition is being checked is itself still a 'running=1' cycle).
    // That extra cycle flows through running_d2 as one spurious captured
    // sample with no counterpart in the MATLAB golden vector -- confirmed
    // by diff: sim output was exactly 1 line longer than golden, and
    // every other line matched bit-for-bit.
    //
    // Fix: hold each sample for one extra cycle before writing it. Only
    // flush the HELD sample once we're back in this block with
    // running_d2 still high (proving the held sample wasn't the final,
    // spurious one). When running_d2 finally drops, the currently-held
    // sample is silently discarded instead of written.
    // ------------------------------------------------------------------------
    reg              have_pending;
    reg signed [7:0] pending_real, pending_imag;

    always @(posedge clk) begin
        if (!rst_n) begin
            have_pending <= 1'b0;
        end else if (running_d2) begin
            if (have_pending) begin
                $fdisplay(fd_real, "%08b", pending_real);
                $fdisplay(fd_imag, "%08b", pending_imag);
            end
            pending_real <= tx_real;
            pending_imag <= tx_imag;
            have_pending <= 1'b1;
        end else begin
            have_pending <= 1'b0;   // drop whatever was pending -- spurious tail cycle
        end
    end

    // ---- Helper Task: reset the golden DQPSK feedback model to its
    //      spec-mandated initial state (all 4 lanes = 1+1j). ----
    task reset_ref_model;
        integer i;
        begin
            for (i = 0; i < 4; i = i + 1) begin
                ref_real_ff[i] = 2'sb01;
                ref_imag_ff[i] = 2'sb01;
            end
        end
    endtask

    // ---- Helper Task: drive one QPSK symbol into the DUT, AND compute
    //      the golden expected DQPSK output for it in lockstep. ----
    task send_symbol(input signed [1:0] in_r, input signed [1:0] in_i);
        reg signed [1:0] exp_r, exp_i;
        begin
            @(negedge clk);
            i_valid = 1'b1;
            Real    = in_r;
            Imag    = in_i;

            exp_r = (in_r * ref_real_ff[3]) - (in_i * ref_imag_ff[3]);
            exp_i = (in_r * ref_imag_ff[3]) + (in_i * ref_real_ff[3]);

            $display("------------------------------------------------------------------------------------------------------------------------");
            $display("[TIME %0t ps] [STIMULUS] Driving Symbol #%0d into Top Module:", $time, symbol_index);
            $display("    > Input Data Vector       : (%2d + j%2d)", in_r, in_i);
            $display("    > DQPSK Shift Register[3] : (%2d + j%2d)", ref_real_ff[3], ref_imag_ff[3]);
            $display("    > DQPSK Math Equation     : (%2d + j%2d) * (%2d + j%2d)", in_r, in_i, ref_real_ff[3], ref_imag_ff[3]);
            $display("                              = [((%2d * %2d) - (%2d * %2d)) + j((%2d * %2d) + (%2d * %2d))]",
                     in_r, ref_real_ff[3], in_i, ref_imag_ff[3], in_r, ref_imag_ff[3], in_i, ref_real_ff[3]);
            $display("                              = (%2d + j%2d)", exp_r, exp_i);

            ref_real_ff[3] = ref_real_ff[2];
            ref_real_ff[2] = ref_real_ff[1];
            ref_real_ff[1] = ref_real_ff[0];
            ref_real_ff[0] = exp_r;

            ref_imag_ff[3] = ref_imag_ff[2];
            ref_imag_ff[2] = ref_imag_ff[1];
            ref_imag_ff[1] = ref_imag_ff[0];
            ref_imag_ff[0] = exp_i;

            exp_dqpsk_r.push_back(exp_r);
            exp_dqpsk_i.push_back(exp_i);
        end
    endtask

    // ---- Helper Task: apply a full synchronous reset to the DUT and
    //      re-initialize the golden model. ----
    task apply_reset;
        begin
            rst_n   = 0;
            i_valid = 0;
            Real    = 0;
            Imag    = 0;
            reset_ref_model();
            repeat (3) @(posedge clk);
            rst_n = 1;
            @(posedge clk);
        end
    endtask

    // ---- Helper Task: load the (Real,Imag) symbol stream from the
    //      selected payload file. Lines starting with "//" are skipped.
    //      Each valid line is parsed as two signed integers. ----
    task automatic load_symbol_file;
        integer fd;
        integer r_read, i_read;
        integer code;
        string line_str;
        sym_t new_sym;
        begin
            fd = $fopen(PAYLOAD_FILE, "r");
            if (fd == 0) begin
                $display("[ERROR] Could not open %s -- check the path/filename.", PAYLOAD_FILE);
                $finish;
            end
            while (!$feof(fd)) begin
                code = $fgets(line_str, fd);
                if (code != 0) begin
                    // Skip comment lines and blank lines
                    if (line_str.len() >= 2 && line_str.substr(0,1) == "//") begin
                        // comment line, skip
                    end else begin
                        code = $sscanf(line_str, "%d %d", r_read, i_read);
                        if (code == 2) begin
                            new_sym.r = r_read[1:0];
                            new_sym.i = i_read[1:0];
                            symbol_queue.push_back(new_sym);
                        end
                    end
                end
            end
            $fclose(fd);
        end
    endtask

    // Main Test Stimulus
    initial begin
        integer blk, sym;
        sym_t cur_sym;

        $display("========================================================================================================================");
        $display("                     STARTING COMPLETE TOP MODULE VERIFICATION PIPELINE (%s)                            ", PAYLOAD_FILE);
        $display("========================================================================================================================");

        clk = 0;

        // ---- Load the (Real,Imag) symbol stream ----
        load_symbol_file();

        num_symbols = symbol_queue.size();

        // Pad with (0,0) neutral entries to a whole number of 4-symbol
        // blocks if the file's symbol count isn't already a multiple of 4.
        // (Not expected for payload1.txt/payload2.txt as generated, but
        // kept for robustness against a differently-sized file.)
        while ((symbol_queue.size() % 4) != 0) begin
            cur_sym.r = 2'sb00;
            cur_sym.i = 2'sb00;
            symbol_queue.push_back(cur_sym);
        end

        num_symbols = symbol_queue.size();
        num_blocks  = num_symbols / 4;

        $display("[TIME %0t ps] [STIMULUS] Loaded %s : %0d symbols -> %0d blocks of 4.",
                  $time, PAYLOAD_FILE, num_symbols, num_blocks);

        apply_reset();

        // ================================================================
        // Drive every block derived from the file, exactly as the
        // original directed testbench drove its hand-written blocks.
        // ================================================================
        for (blk = 0; blk < num_blocks; blk = blk + 1) begin
            for (sym = 0; sym < 4; sym = sym + 1) begin
                cur_sym = symbol_queue.pop_front();
                send_symbol(cur_sym.r, cur_sym.i);
            end

            // De-assert valid between blocks
            @(negedge clk);
            i_valid = 1'b0;
            Real    = 2'sb00;
            Imag    = 2'sb00;
            $display("[TIME %0t ps] [STIMULUS] De-asserting i_valid. Inserting Inter-frame Gap...", $time);
            repeat (2) @(posedge clk);
        end

        $display("========================================================================================================================");
        $display("[TIME %0t ps] All %0d file-derived symbols pushed. Waiting for tx_done...", $time, num_symbols);
        $display("========================================================================================================================");
        @(posedge tx_done);
        $display("[TIME %0t ps] tx_done Detected HIGH.", $time);
        repeat (10) @(posedge clk);

        // ---- Verification Results Summary ----
        $display("========================================================================================================================");
        $display("                                    FINAL VERIFICATION REPORT (%s RUN)                                         ", PAYLOAD_FILE);
        $display("========================================================================================================================");
        $display("  > TOTAL CHECKS PASSED           : %0d", pass_cnt);
        $display("  > TOTAL CHECKS FAILED           : %0d", fail_cnt);
        $display("  > TOTAL DQPSK SYMBOLS PROCESSED : %0d", symbol_index);
        $display("  > TOTAL MODULATION SAMPLES CHEKD: %0d", modulation_sample_cnt);
        if (fail_cnt == 0 && pass_cnt > 0) begin
            $display("  > FINAL STATUS                  : TESTBENCH PASSED SUCCESSFULLY! (file-driven stimulus fully verified end-to-end)");
        end else begin
            $display("  > FINAL STATUS                  : TESTBENCH FAILED WITH ERRORS!");
        end
        $display("========================================================================================================================");

        $fclose(fd_real);
        $fclose(fd_imag);
        $display("[TIME %0t ps] Sim output vectors written: tx_real_sim_output.txt, tx_imag_sim_output.txt", $time);

        $stop;
    end

    // ========================================================================
    // MONITOR 1: Self-checking DQPSK output verification. Unchanged.
    // ========================================================================
    always @(posedge clk) begin
        if (rst_n && Top_DUT.DQPSK_DUT.valid) begin
            if (exp_dqpsk_r.size() > 0) begin
                reg signed [1:0] expected_r, expected_i;
                expected_r = exp_dqpsk_r.pop_front();
                expected_i = exp_dqpsk_i.pop_front();

                if (Top_DUT.DQPSK_DUT.Real_o === expected_r && Top_DUT.DQPSK_DUT.Imag_o === expected_i) begin
                    $display("[TIME %0t ps] [DQPSK MATCH] Symbol #%0d successfully encoded and written to FIFO:", $time, symbol_index);
                    $display("    > HW Output Vector : (%2d + j%2d)", Top_DUT.DQPSK_DUT.Real_o, Top_DUT.DQPSK_DUT.Imag_o);
                    $display("    > Golden Expected  : (%2d + j%2d)", expected_r, expected_i);
                    $display("    > Verification     : MATCH SUCCESSFUL [PASSED]");
                    pass_cnt = pass_cnt + 1;
                end else begin
                    $display("[TIME %0t ps] [DQPSK ERROR] Symbol #%0d Mismatch Detected:", $time, symbol_index);
                    $display("    > HW Output Vector : (%2d + j%2d)", Top_DUT.DQPSK_DUT.Real_o, Top_DUT.DQPSK_DUT.Imag_o);
                    $display("    > Golden Expected  : (%2d + j%2d)", expected_r, expected_i);
                    $display("    > Verification     : MISMATCH DETECTED [FAILED]");
                    fail_cnt = fail_cnt + 1;
                end
                symbol_index = symbol_index + 1;
            end
        end
    end

    // ========================================================================
    // MONITOR 2: Self-checking complex multiplier verification. Unchanged.
    // ========================================================================
    always @(posedge clk) begin
        if (rst_n && Top_DUT.CSK_GEN_DUT.running && Top_DUT.next_item) begin
            reg signed [7:0] calc_tx_real, calc_tx_imag;
            reg signed [1:0]  s_r_val, s_i_val;
            reg signed [5:0]  csk_r_val, csk_i_val;
            real float_csk_r, float_csk_i;
            real float_tx_r, float_tx_i;

            s_r_val   = Top_DUT.S_R;
            s_i_val   = Top_DUT.S_I;
            csk_r_val = Top_DUT.csk_out_r;
            csk_i_val = Top_DUT.csk_out_i;

            float_csk_r = $itor(csk_r_val) / 16.0;
            float_csk_i = $itor(csk_i_val) / 16.0;

            calc_tx_real = (s_r_val * csk_r_val) - (s_i_val * csk_i_val);
            calc_tx_imag = (s_r_val * csk_i_val) + (s_i_val * csk_r_val);

            float_tx_r = $itor(calc_tx_real) / 16.0;
            float_tx_i = $itor(calc_tx_imag) / 16.0;

            @(posedge clk);
            if (tx_real === calc_tx_real && tx_imag === calc_tx_imag) begin
                $display("[TIME %0t ps] [TX MODULATOR] Complex Chirp Multiplication Sample #%0d:", $time, modulation_sample_cnt);
                $display("    > Read Symbol Vector (S_R + j S_I)  : (%2d + j%2d)", s_r_val, s_i_val);
                $display("    > ROM Wave Vector (csk_out_r, _i)    : Raw Fixed-Point Q1.4 = (%3d + j%3d) | Math Float = (%6.4f + j%6.4f)",
                         csk_r_val, csk_i_val, float_csk_r, float_csk_i);
                $display("    > Complex Operation                 : (%2d + j%2d) * (%6.4f + j%6.4f)",
                         s_r_val, s_i_val, float_csk_r, float_csk_i);
                $display("    > Math Expansion                    : [((%2d * %6.4f) - (%2d * %6.4f)) + j((%2d * %6.4f) + (%2d * %6.4f))]",
                         s_r_val, float_csk_r, s_i_val, float_csk_i, s_r_val, float_csk_i, s_i_val, float_csk_r);
                $display("    > Hardware Output (tx_real + j tx_imag): Raw Q3.4 Integer = (%4d + j%4d) | Math Float = (%7.4f + j%7.4f)",
                         tx_real, tx_imag, float_tx_r, float_tx_i);
                $display("    > Modulator Verification            : MATCH SUCCESSFUL [PASSED]");
                $display("------------------------------------------------------------------------------------------------------------------------");
                pass_cnt = pass_cnt + 1;
            end else begin
                $display("[TIME %0t ps] [TX MODULATOR ERROR] Mismatch at Sample #%0d:", $time, modulation_sample_cnt);
                $display("    > Read Symbol Vector (S_R + j S_I)  : (%2d + j%2d)", s_r_val, s_i_val);
                $display("    > ROM Wave Vector (csk_out_r, _i)    : Raw Fixed-Point Q1.4 = (%3d + j%3d) | Math Float = (%6.4f + j%6.4f)",
                         csk_r_val, csk_i_val, float_csk_r, float_csk_i);
                $display("    > HW Output (tx_real, tx_imag)      : (%4d + j%4d)", tx_real, tx_imag);
                $display("    > Expected Output                   : (%4d + j%4d)", calc_tx_real, calc_tx_imag);
                $display("    > Modulator Verification            : MISMATCH DETECTED [FAILED]");
                $display("------------------------------------------------------------------------------------------------------------------------");
                fail_cnt = fail_cnt + 1;
            end
            modulation_sample_cnt = modulation_sample_cnt + 1;
        end
    end

endmodule