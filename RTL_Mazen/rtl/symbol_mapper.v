module symbol_mapper #(
/********************************** Parameters *********************************/
    parameter rate_mode = "H"
)(
/************************************ Inputs ***********************************/
    input                                       clk,
    input                                       rst_n, 
    input                                       mode,
    input      [(rate_mode == "F"? 2 : 5):0]    i_data,
    input                                       i_valid,
/*********************************** Outputs ***********************************/
    output reg [(rate_mode == "F"? 3 : 31):0]   o_data,
    output reg                                  o_valid
);

generate
    if (rate_mode == "F") begin : gen_mapper_1mbps
        always @(posedge clk) 
        begin
            if (!rst_n) 
            begin
                o_data  <= 4'b0;
                o_valid <= 1'b0;
            end 
            else 
            begin
                o_valid <= i_valid;
                if (i_valid) 
                begin
                    case (i_data[1:0])
                        2'd0, 2'd2: o_data <= i_data[2] ? ~4'b1111 : 4'b1111;
                        2'd1, 2'd3: o_data <= i_data[2] ? ~4'b1010 : 4'b1010;
                        default:    o_data <= 4'b0;
                    endcase
                end
            end
        end
    end 
    else if (rate_mode == "S") begin : gen_mapper_250kbps
        always @(posedge clk) begin
            if (!rst_n) 
            begin
                o_data  <= 32'b0;
                o_valid <= 1'b0;
            end 
            else 
            begin
                o_valid <= i_valid;
                if (i_valid) 
                begin
                    case (i_data[4:0])
                        5'd0, 5'd16:  o_data <= i_data[5] ? ~32'b11111111111111111111111111111111 : 32'b11111111111111111111111111111111;
                        5'd1, 5'd17:  o_data <= i_data[5] ? ~32'b10101010101010101010101010101010 : 32'b10101010101010101010101010101010;
                        5'd2, 5'd18:  o_data <= i_data[5] ? ~32'b11001100110011001100110011001100 : 32'b11001100110011001100110011001100;
                        5'd3, 5'd19:  o_data <= i_data[5] ? ~32'b10011001100110011001100110011001 : 32'b10011001100110011001100110011001;
                        5'd4, 5'd20:  o_data <= i_data[5] ? ~32'b11110000111100001111000011110000 : 32'b11110000111100001111000011110000;
                        5'd5, 5'd21:  o_data <= i_data[5] ? ~32'b10100101101001011010010110100101 : 32'b10100101101001011010010110100101;
                        5'd6, 5'd22:  o_data <= i_data[5] ? ~32'b11000011110000111100001111000011 : 32'b11000011110000111100001111000011;
                        5'd7, 5'd23:  o_data <= i_data[5] ? ~32'b10010110100101101001011010010110 : 32'b10010110100101101001011010010110;
                        5'd8, 5'd24:  o_data <= i_data[5] ? ~32'b11111111000000001111111100000000 : 32'b11111111000000001111111100000000;
                        5'd9, 5'd25:  o_data <= i_data[5] ? ~32'b10101010010101011010101001010101 : 32'b10101010010101011010101001010101;
                        5'd10, 5'd26: o_data <= i_data[5] ? ~32'b11001100001100111100110000110011 : 32'b11001100001100111100110000110011;
                        5'd11, 5'd27: o_data <= i_data[5] ? ~32'b10011001011001101001100101100110 : 32'b10011001011001101001100101100110;
                        5'd12, 5'd28: o_data <= i_data[5] ? ~32'b11110000000011111111000000001111 : 32'b11110000000011111111000000001111;
                        5'd13, 5'd29: o_data <= i_data[5] ? ~32'b10100101010110101010010101011010 : 32'b10100101010110101010010101011010;
                        5'd14, 5'd30: o_data <= i_data[5] ? ~32'b11000011001111001100001100111100 : 32'b11000011001111001100001100111100;
                        5'd15, 5'd31: o_data <= i_data[5] ? ~32'b10010110011010011001011001101001 : 32'b10010110011010011001011001101001;
                        default:     o_data <= 32'b0;
                    endcase
                end
            end
        end
    end
    else if (rate_mode == "H") begin : gen_mapper_hybrid
        always @(posedge clk) begin
            if (!rst_n) 
            begin
                o_data  <= 32'b0;
                o_valid <= 1'b0;
            end 
            else 
            begin
                o_valid <= i_valid;
                if (i_valid) 
                begin
                    if (!mode) begin
                        // Standard 250 Kbps mapping behavior when mode is 0
                        case (i_data[4:0])
                            5'd0, 5'd16:  o_data <= i_data[5] ? ~32'b11111111111111111111111111111111 : 32'b11111111111111111111111111111111;
                            5'd1, 5'd17:  o_data <= i_data[5] ? ~32'b10101010101010101010101010101010 : 32'b10101010101010101010101010101010;
                            5'd2, 5'd18:  o_data <= i_data[5] ? ~32'b11001100110011001100110011001100 : 32'b11001100110011001100110011001100;
                            5'd3, 5'd19:  o_data <= i_data[5] ? ~32'b10011001100110011001100110011001 : 32'b10011001100110011001100110011001;
                            5'd4, 5'd20:  o_data <= i_data[5] ? ~32'b11110000111100001111000011110000 : 32'b11110000111100001111000011110000;
                            5'd5, 5'd21:  o_data <= i_data[5] ? ~32'b10100101101001011010010110100101 : 32'b10100101101001011010010110100101;
                            5'd6, 5'd22:  o_data <= i_data[5] ? ~32'b11000011110000111100001111000011 : 32'b11000011110000111100001111000011;
                            5'd7, 5'd23:  o_data <= i_data[5] ? ~32'b10010110100101101001011010010110 : 32'b10010110100101101001011010010110;
                            5'd8, 5'd24:  o_data <= i_data[5] ? ~32'b11111111000000001111111100000000 : 32'b11111111000000001111111100000000;
                            5'd9, 5'd25:  o_data <= i_data[5] ? ~32'b10101010010101011010101001010101 : 32'b10101010010101011010101001010101;
                            5'd10, 5'd26: o_data <= i_data[5] ? ~32'b11001100001100111100110000110011 : 32'b11001100001100111100110000110011;
                            5'd11, 5'd27: o_data <= i_data[5] ? ~32'b10011001011001101001100101100110 : 32'b10011001011001101001100101100110;
                            5'd12, 5'd28: o_data <= i_data[5] ? ~32'b11110000000011111111000000001111 : 32'b11110000000011111111000000001111;
                            5'd13, 5'd29: o_data <= i_data[5] ? ~32'b10100101010110101010010101011010 : 32'b10100101010110101010010101011010;
                            5'd14, 5'd30: o_data <= i_data[5] ? ~32'b11000011001111001100001100111100 : 32'b11000011001111001100001100111100;
                            5'd15, 5'd31: o_data <= i_data[5] ? ~32'b10010110011010011001011001101001 : 32'b10010110011010011001011001101001;
                            default:     o_data <= 32'b0;
                        endcase
                    end 
                    else begin
                        // Mode is 1: Output keeps 32-bit width, but only 4 bits are active ([3:0]) and rest are 0
                        o_data[31:4] <= 28'b0;
                        case (i_data[1:0])
                            2'd0, 2'd2: o_data[3:0] <= i_data[2] ? ~4'b1111 : 4'b1111;
                            2'd1, 2'd3: o_data[3:0] <= i_data[2] ? ~4'b1010 : 4'b1010;
                            default:    o_data[3:0] <= 4'b0;
                        endcase
                    end
                end
            end
        end
    end
endgenerate

endmodule