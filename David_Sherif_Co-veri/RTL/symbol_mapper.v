                            6'b011111: o_data <= 32'b10010110011010010110100110010110;
                            6'b100000: o_data <= 32'b00000000000000000000000000000000;
                            6'b100001: o_data <= 32'b01010101010101010101010101010101;
                            6'b100010: o_data <= 32'b00110011001100110011001100110011;
                            6'b100011: o_data <= 32'b01100110011001100110011001100110;
                            6'b100100: o_data <= 32'b00001111000011110000111100001111;
                            6'b100101: o_data <= 32'b01011010010110100101101001011010;
                            6'b100110: o_data <= 32'b00111100001111000011110000111100;
                            6'b100111: o_data <= 32'b01101001011010010110100101101001;
                            6'b101000: o_data <= 32'b00000000111111110000000011111111;
                            6'b101001: o_data <= 32'b01010101101010100101010110101010;
                            6'b101010: o_data <= 32'b00110011110011000011001111001100;
