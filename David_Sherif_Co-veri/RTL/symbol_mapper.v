module symbol_mapper #(
/********************************** Parameters *********************************/
    parameter rate_mode = "H"
)(
/************************************ Inputs ***********************************/
    input                                       clk,
    input                                       rst_n, 
    input                                       mode,
    input        [(rate_mode == "F"? 2 : 5):0]  i_data,
    input                                       i_valid,
/*********************************** Outputs ***********************************/
    output reg   [(rate_mode == "F"? 3 : 31):0] o_data,
    output reg                                  o_valid
);

generate
    if (rate_mode == "F") begin : gen_mapper_1mbps
        always @(posedge clk) 
        begin
            if (!rst_n) 
            begin
                o_data  <= 4'b0;
                o_valid <= 1'b0;
            end 
            else 
            begin
                o_valid <= i_valid;
                if (i_valid) 
                begin
                    case (i_data[1:0])
                        2'd0: o_data <= i_data[2] ? ~4'b1111 : 4'b1111;
                        2'd1: o_data <= i_data[2] ? ~4'b1010 : 4'b1010;
                        2'd2: o_data <= i_data[2] ? ~4'b1100 : 4'b1100;
                        2'd3: o_data <= i_data[2] ? ~4'b1001 : 4'b1001;
                        default: o_data <= 4'b0;
                    endcase
                end
            end
        end
    end 
